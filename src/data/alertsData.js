export function getActiveAlerts() {
  return alertsData.filter(a => !a.acknowledged || a.actionRequired)
}

export function getAlertsByCrewId(crewId) {
  return alertsData.filter(a => a.crewId === crewId || a.astronautId === crewId || a.crewId === null)
}

export function getAlertsBySeverity(severity) {
  return alertsData.filter(a => a.severity === severity)
}

export function getAlertCounts() {
  return {
    critical: alertsData.filter(a => a.severity === 'critical' && !a.acknowledged).length,
    warning: alertsData.filter(a => a.severity === 'warning' && !a.acknowledged).length,
    info: alertsData.filter(a => a.severity === 'info').length,
    nominal: alertsData.filter(a => a.severity === 'nominal').length,
    total: alertsData.length,
    active: alertsData.filter(a => !a.acknowledged || a.actionRequired).length,
  }
}
