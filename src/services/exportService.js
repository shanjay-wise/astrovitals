/**
 * Export Service
 * Generates formatted PDF medical logs & CSV raw telemetry files
 */

import { jsPDF } from 'jspdf'

export const exportService = {
  /**
   * Export comprehensive astronaut medical summary to PDF
   */
  exportAstronautPdf: (astronaut, currentVitals, alerts = []) => {
    try {
      const doc = new jsPDF()
      const pageWidth = doc.internal.pageSize.getWidth()

      // Header
      doc.setFillColor(11, 61, 145) // NASA Blue
      doc.rect(0, 0, pageWidth, 26, 'F')

      doc.setTextColor(255, 255, 255)
      doc.setFontSize(16)
      doc.setFont('helvetica', 'bold')
      doc.text('ASTROVITALS | NASA BIO-MEDICAL TELEMETRY REPORT', 14, 12)

      doc.setFontSize(9)
      doc.setFont('helvetica', 'normal')
      doc.text('Team Proxyma Dynamics • NASA Space Apps Challenge 2026', 14, 20)

      const dateStr = new Date().toUTCString()
      doc.text(dateStr, pageWidth - 14, 20, { align: 'right' })

      // Subject Info Box
      doc.setTextColor(11, 18, 32)
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('ASTRONAUT PROFILE', 14, 38)

      doc.setFontSize(10)
      doc.setFont('helvetica', 'normal')
      doc.text(`Name: ${astronaut.name}`, 14, 46)
      doc.text(`Role: ${astronaut.role}`, 14, 52)
      doc.text(`Mission: ${astronaut.mission} (MET Day ${astronaut.missionDay})`, 14, 58)
      doc.text(`Biometrics: Age ${astronaut.age} • ${astronaut.sex.toUpperCase()} • ${astronaut.heightCm} cm • ${astronaut.weightKg} kg • Blood: ${astronaut.bloodType}`, 14, 64)

      // Divider line
      doc.setDrawColor(200, 210, 230)
      doc.line(14, 70, pageWidth - 14, 70)

      // Realtime Telemetry Grid
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('CURRENT FLIGHT TELEMETRY SNAPSHOT', 14, 80)

      const vitalsList = [
        ['Heart Rate', `${currentVitals?.hr || astronaut.baselines.hr} bpm`, `Baseline: ${astronaut.baselines.hr} bpm`],
        ['Blood Pressure', `${currentVitals?.bpSys || 118}/${currentVitals?.bpDia || 76} mmHg`, 'MAP: 90 mmHg'],
        ['SpO2 (Pulse Ox)', `${currentVitals?.spo2 || 98.2}%`, 'Permissible: >95.0%'],
        ['Core Body Temp', `${currentVitals?.coreTemp || 36.7} °C`, 'Circadian peak'],
        ['Heart Rate Var. (RMSSD)', `${currentVitals?.hrv || 48} ms`, 'Target: >35 ms'],
        ['Cabin ppCO2 (CDRA)', `${currentVitals?.cabinCO2 || 2.1} mmHg`, 'NASA-STD-3001: <3.0 mmHg'],
        ['Radiation Dose Rate', `${currentVitals?.radiationRate || 0.042} mSv/hr`, 'Deep space GCR baseline'],
        ['Hydration Status', `${currentVitals?.hydration || 91}%`, 'Target: >85%'],
        ['Bone Density Retained', `${currentVitals?.boneDensity || 98}%`, 'ARED preserved'],
        ['Muscle Mass Volume', `${currentVitals?.muscleMass || 96}%`, 'Target: >90%']
      ]

      let y = 90
      doc.setFontSize(9)
      vitalsList.forEach(([metric, val, note]) => {
        doc.setFont('helvetica', 'bold')
        doc.text(metric, 14, y)
        doc.setFont('helvetica', 'normal')
        doc.text(val, 90, y)
        doc.setTextColor(100, 116, 139)
        doc.text(note, 130, y)
        doc.setTextColor(11, 18, 32)
        y += 7
      })

      // Active Alerts Section
      doc.line(14, y + 2, pageWidth - 14, y + 2)
      y += 10
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('ACTIVE BIO-TELEMETRY ALERTS & CLINICAL DIRECTIVES', 14, y)

      y += 8
      doc.setFontSize(9)
      if (!alerts || alerts.length === 0) {
        doc.setFont('helvetica', 'italic')
        doc.text('No active alerts. All vital channels operating within nominal NASA-STD-3001 limits.', 14, y)
      } else {
        alerts.slice(0, 5).forEach((alt, idx) => {
          doc.setFont('helvetica', 'bold')
          doc.setTextColor(alt.severity === 'critical' ? 239 : 245, alt.severity === 'critical' ? 68 : 158, alt.severity === 'critical' ? 68 : 11)
          doc.text(`[${alt.severity.toUpperCase()}] ${alt.title || alt.metric}:`, 14, y)
          doc.setTextColor(11, 18, 32)
          doc.setFont('helvetica', 'normal')
          doc.text(alt.message || alt.description, 14, y + 5, { maxWidth: pageWidth - 28 })
          doc.setTextColor(11, 61, 145)
          doc.text(`Recommendation: ${alt.recommendation}`, 14, y + 10, { maxWidth: pageWidth - 28 })
          y += 18
        })
      }

      // Footer
      doc.setFontSize(8)
      doc.setTextColor(148, 163, 184)
      doc.text('NASA Flight Surgeon Console • Confidential Astronaut Medical Record • Generated by AstroVitals', 14, 285)

      doc.save(`AstroVitals_${astronaut.id}_Day${astronaut.missionDay}.pdf`)
      return true
    } catch (err) {
      console.error('[ExportService] PDF export error:', err)
      return false
    }
  },

  /**
   * Export telemetry to CSV format
   */
  exportTelemetryCsv: (astronaut, vitalsHistory = []) => {
    try {
      const headers = ['Timestamp', 'AstronautID', 'HeartRate_bpm', 'BPSystolic_mmHg', 'BPDiastolic_mmHg', 'SpO2_pct', 'CoreTemp_C', 'CabinCO2_mmHg', 'RadiationRate_mSv_hr', 'Hydration_pct']
      const rows = vitalsHistory.length > 0 ? vitalsHistory : [
        [new Date().toISOString(), astronaut.id, astronaut.baselines.hr, astronaut.baselines.bpSys, astronaut.baselines.bpDia, astronaut.baselines.spo2, astronaut.baselines.coreTemp, 2.1, 0.042, astronaut.baselines.hydration]
      ]

      const csvContent = 'data:text/csv;charset=utf-8,' +
        [headers.join(','), ...rows.map(e => Array.isArray(e) ? e.join(',') : Object.values(e).join(','))].join('\n')

      const encodedUri = encodeURI(csvContent)
      const link = document.createElement('a')
      link.setAttribute('href', encodedUri)
      link.setAttribute('download', `AstroVitals_Telemetry_${astronaut.id}.csv`)
      document.body.appendChild(link)
      link.click()
      document.body.removeChild(link)
      return true
    } catch (err) {
      console.error('[ExportService] CSV export error:', err)
      return false
    }
  }
}
